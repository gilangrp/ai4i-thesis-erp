#!/usr/bin/env python3
"""
Convert ai4i2020.csv -> file .sql berisi INSERT INTO untuk Oracle 26ai (23ai+).

Script ini HANYA menghasilkan file SQL. DDL (CREATE TABLE) dan eksekusi insert
dikerjakan manual. Nama kolom tujuan (urutan = urutan kolom CSV):

    UDI, PRODUCT_ID, TYPE, AIR_TEMP_K, PROCESS_TEMP_K, RPM, TORQUE_NM,
    TOOL_WEAR_MIN, MACHINE_FAILURE, TWF, HDF, PWF, OSF, RNF

Contoh:
    python scripts/csv_to_oracle_insert.py \
        --csv data/ai4i2020.csv --out sql/insert_ai4i2020.sql \
        --table AI4I_2020 --schema MYSCHEMA

Style output:
    multirow (default) : INSERT INTO t (cols) VALUES (...),(...);  -> Oracle 23ai/26ai,
                         maksimal 1000 baris per statement.
    single             : satu INSERT per baris (paling kompatibel, paling lambat).
"""
import argparse
import csv
import re
import sys
from pathlib import Path

# (nama kolom Oracle, tipe) sesuai urutan kolom CSV.
COLUMNS = [
    ("UDI", "int"), ("PRODUCT_ID", "str"), ("TYPE", "str"),
    ("AIR_TEMP_K", "float"), ("PROCESS_TEMP_K", "float"), ("RPM", "int"),
    ("TORQUE_NM", "float"), ("TOOL_WEAR_MIN", "int"), ("MACHINE_FAILURE", "int"),
    ("TWF", "int"), ("HDF", "int"), ("PWF", "int"), ("OSF", "int"), ("RNF", "int"),
]
IDENT = re.compile(r"^[A-Za-z][A-Za-z0-9_$#]*(\.[A-Za-z][A-Za-z0-9_$#]*)?$")


def literal(raw: str, kind: str) -> str:
    raw = raw.strip()
    if raw == "":
        return "NULL"
    if kind == "int":
        return str(int(raw))
    if kind == "float":
        float(raw)  # validasi saja; teks asli dipertahankan agar presisi tidak berubah
        return raw
    return "'" + raw.replace("'", "''") + "'"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", default="data/ai4i2020.csv")
    ap.add_argument("--out", default="sql/insert_ai4i2020.sql")
    ap.add_argument("--table", default="AI4I_2020")
    ap.add_argument("--schema", default=None, help="prefix schema, opsional")
    ap.add_argument("--batch-size", type=int, default=500, help="baris per INSERT (maks 1000)")
    ap.add_argument("--style", choices=["multirow", "single"], default="multirow")
    args = ap.parse_args()

    if not 1 <= args.batch_size <= 1000:
        sys.exit("--batch-size harus 1..1000 (batas Oracle untuk multi-row VALUES)")
    target = f"{args.schema}.{args.table}" if args.schema else args.table
    if not IDENT.match(target):
        sys.exit(f"Nama tabel tidak valid: {target}")

    col_list = ", ".join(c for c, _ in COLUMNS)
    head = f"INSERT INTO {target} ({col_list}) VALUES"
    batch = 1 if args.style == "single" else args.batch_size

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    total = 0
    with open(args.csv, newline="", encoding="utf-8-sig") as fin, \
         open(args.out, "w", encoding="utf-8", newline="\n") as fout:
        reader = csv.reader(fin)
        header = next(reader)
        if len(header) != len(COLUMNS):
            sys.exit(f"CSV punya {len(header)} kolom, diharapkan {len(COLUMNS)}")

        fout.write(f"-- Generated by csv_to_oracle_insert.py dari {Path(args.csv).name}\n")
        fout.write(f"-- Target: {target} | style: {args.style}\n\n")

        buf = []

        def flush():
            if not buf:
                return
            if args.style == "single":
                fout.write(f"{head} {buf[0]};\n")
            else:
                fout.write(head + "\n  " + ",\n  ".join(buf) + ";\n\n")
            buf.clear()

        for lineno, row in enumerate(reader, start=2):
            if not row:
                continue
            if len(row) != len(COLUMNS):
                sys.exit(f"Baris {lineno}: jumlah kolom {len(row)} != {len(COLUMNS)}")
            try:
                vals = [literal(v, k) for v, (_, k) in zip(row, COLUMNS)]
            except ValueError as e:
                sys.exit(f"Baris {lineno}: nilai tidak valid ({e})")
            buf.append("(" + ", ".join(vals) + ")")
            total += 1
            if len(buf) >= batch:
                flush()
        flush()
        fout.write("COMMIT;\n")

    print(f"OK: {total} baris -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
