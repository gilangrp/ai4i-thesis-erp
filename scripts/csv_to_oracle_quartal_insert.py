#!/usr/bin/env python3
"""
Convert ai4i2020.csv -> file-file .sql untuk Oracle 23ai / 26ai (Quartal & Weekly).

Dataset 10.000 baris diacak (shuffle) secara random tanpa duplikat, kemudian dibagi menjadi:
- Data Training (8.000 data):
    sql/quartal/training/training.sql
- Data Weekly (2.000 data, 250 data per minggu = 8 minggu):
    sql/quartal/weekly/week1.sql
    sql/quartal/weekly/week2.sql
    ...
    sql/quartal/weekly/week8.sql

Total data: 8.000 + (8 x 250) = 10.000 data (seluruh baris dataset tanpa duplikat).

Contoh:
    python scripts/csv_to_oracle_quartal_insert.py
    python scripts/csv_to_oracle_quartal_insert.py --seed 42 --table MACHINE_OPERATION
"""
import argparse
import csv
import random
import re
import sys
from pathlib import Path

# (nama kolom Oracle, tipe) sesuai urutan kolom CSV.
COLUMNS = [
    ("UDI", "int"), ("PRODUCT_ID", "str"), ("TYPE", "str"),
    ("AIR_TEMP_K", "float"), ("PROCESS_TEMP_K", "float"), ("RPM", "int"),
    ("TORQUE_NM", "float"), ("TOOL_WEAR_MIN", "int"), ("MACHINE_FAILURE", "int"),
    ("TWF", "int"), ("HDF", "int"), ("PWF", "int"), ("OSF", "int"), ("RNF", "int"),
]
IDENT = re.compile(r"^[A-Za-z][A-Za-z0-9_$#]*(\.[A-Za-z][A-Za-z0-9_$#]*)?$")


def literal(raw: str, kind: str) -> str:
    raw = raw.strip()
    if raw == "":
        return "NULL"
    if kind == "int":
        return str(int(raw))
    if kind == "float":
        float(raw)  # validasi saja; teks asli dipertahankan agar presisi tidak berubah
        return raw
    return "'" + raw.replace("'", "''") + "'"


def write_sql_file(out_path: Path, rows: list, col_list: str, target: str,
                   style: str, batch_size: int, title: str, seed: int = None):
    """Menulis list baris data CSV ke dalam file SQL INSERT Oracle."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    head = f"INSERT INTO {target} ({col_list}) VALUES"
    batch = 1 if style == "single" else batch_size

    with open(out_path, "w", encoding="utf-8", newline="\n") as fout:
        fout.write(f"-- Generated by csv_to_oracle_quartal_insert.py\n")
        fout.write(f"-- Kategori: {title}\n")
        fout.write(f"-- Jumlah baris: {len(rows)} | Target: {target} | style: {style}\n")
        if seed is not None:
            fout.write(f"-- Random seed: {seed}\n")
        fout.write("\n")

        buf = []

        def flush():
            if not buf:
                return
            if style == "single":
                fout.write(f"{head} {buf[0]};\n")
            else:
                fout.write(head + "\n  " + ",\n  ".join(buf) + ";\n\n")
            buf.clear()

        for idx, row in enumerate(rows, start=1):
            try:
                vals = [literal(v, k) for v, (_, k) in zip(row, COLUMNS)]
            except ValueError as e:
                sys.exit(f"Data index {idx}: nilai tidak valid ({e})")
            buf.append("(" + ", ".join(vals) + ")")
            if len(buf) >= batch:
                flush()
        flush()
        fout.write("COMMIT;\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", default="data/ai4i2020.csv", help="path ke file ai4i2020.csv")
    ap.add_argument("--out-dir", default="sql/quartal", help="direktori utama output SQL")
    ap.add_argument("--table", default="MACHINE_OPERATION", help="nama tabel Oracle")
    ap.add_argument("--schema", default=None, help="prefix schema Oracle (opsional)")
    ap.add_argument("--train-size", type=int, default=8000, help="jumlah baris data training (default: 8000)")
    ap.add_argument("--week-size", type=int, default=250, help="jumlah baris per weekly file (default: 250)")
    ap.add_argument("--seed", type=int, default=42, help="random seed untuk reproducibility shuffle (default: 42, isi -1 untuk random tanpa seed)")
    ap.add_argument("--batch-size", type=int, default=500, help="baris per INSERT untuk multirow (maks 1000)")
    ap.add_argument("--style", choices=["multirow", "single"], default="multirow")
    args = ap.parse_args()

    if not 1 <= args.batch_size <= 1000:
        sys.exit("--batch-size harus 1..1000 (batas Oracle untuk multi-row VALUES)")
    target = f"{args.schema}.{args.table}" if args.schema else args.table
    if not IDENT.match(target):
        sys.exit(f"Nama tabel tidak valid: {target}")

    csv_path = Path(args.csv)
    if not csv_path.exists():
        sys.exit(f"File CSV tidak ditemukan: {csv_path}")

    # Baca seluruh baris dari CSV
    with open(csv_path, newline="", encoding="utf-8-sig") as fin:
        reader = csv.reader(fin)
        header = next(reader)
        if len(header) != len(COLUMNS):
            sys.exit(f"CSV punya {len(header)} kolom, diharapkan {len(COLUMNS)}")
        all_rows = [row for row in reader if row]

    total_rows = len(all_rows)
    print(f"Total baris dibaca dari CSV: {total_rows}")

    if total_rows < args.train_size:
        sys.exit(f"Jumlah baris CSV ({total_rows}) kurang dari train-size ({args.train_size})")

    # Acak data dari awal agar training dan weekly terdistribusi secara random tanpa duplikat
    actual_seed = None if args.seed == -1 else args.seed
    rng = random.Random(actual_seed)
    shuffled_rows = list(all_rows)
    rng.shuffle(shuffled_rows)

    # 1. Alokasi Data Training (default: 8000 baris)
    training_rows = shuffled_rows[:args.train_size]

    # 2. Alokasi Data Sisanya untuk Weekly (default: 2000 baris)
    remaining_rows = shuffled_rows[args.train_size:]
    weekly_total = len(remaining_rows)

    col_list = ", ".join(c for c, _ in COLUMNS)
    base_out = Path(args.out_dir)

    # Export Training Data
    train_file = base_out / "training" / "training.sql"
    write_sql_file(
        out_path=train_file,
        rows=training_rows,
        col_list=col_list,
        target=target,
        style=args.style,
        batch_size=args.batch_size,
        title="Training Dataset",
        seed=actual_seed
    )
    print(f"✔ Training SQL berhasil dibuat: {train_file} ({len(training_rows)} baris)")

    # Export Weekly Data (dibagi per week-size, default 250)
    weekly_dir = base_out / "weekly"
    num_weeks = (weekly_total + args.week_size - 1) // args.week_size if args.week_size > 0 else 0

    total_weekly_written = 0
    for w in range(num_weeks):
        start_idx = w * args.week_size
        end_idx = min(start_idx + args.week_size, weekly_total)
        week_rows = remaining_rows[start_idx:end_idx]
        week_file = weekly_dir / f"week{w + 1}.sql"
        write_sql_file(
            out_path=week_file,
            rows=week_rows,
            col_list=col_list,
            target=target,
            style=args.style,
            batch_size=args.batch_size,
            title=f"Weekly Dataset - Week {w + 1}",
            seed=actual_seed
        )
        total_weekly_written += len(week_rows)
        print(f"✔ Weekly SQL berhasil dibuat: {week_file} ({len(week_rows)} baris)")

    print("\n" + "=" * 50)
    print("RINGKASAN EKSPOR:")
    print(f"• Training : {len(training_rows)} baris ({train_file})")
    print(f"• Weekly   : {total_weekly_written} baris terbagi ke {num_weeks} file ({weekly_dir}/week1.sql - week{num_weeks}.sql)")
    print(f"• Total    : {len(training_rows) + total_weekly_written} baris (seluruh data teralokasi unik tanpa duplikat)")
    print("=" * 50)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
